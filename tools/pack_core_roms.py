#!/usr/bin/env python3
"""Generate 40-bit MIFs for the single-port BBC and cartridge ROM stores."""

from __future__ import annotations

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ROMS = ROOT / "roms"
ROM_BYTES = 256 * 1024
SLOT_BYTES = 16 * 1024


def parse_byte_mif(path: Path, size: int) -> bytearray:
    data = bytearray(size)
    in_content = False
    address = 0
    for raw in path.read_text(encoding="ascii").splitlines():
        line = raw.strip()
        if line == "CONTENT BEGIN":
            in_content = True
            continue
        if not in_content or not line or line == "END;" or line.startswith("--"):
            continue
        if ":" not in line or ".." in line:
            continue
        left, right = line.rstrip(";").split(":", 1)
        address = int(left.strip(), 16)
        for value in right.split():
            if address < size:
                data[address] = int(value, 16)
            address += 1
    return data


def parse_packed_mif(path: Path, size: int) -> bytearray:
    data = bytearray(size)
    in_content = False
    lanes = None
    for raw in path.read_text(encoding="ascii").splitlines():
        line = raw.strip()
        if line.startswith("WIDTH"):
            lanes = int(line.split("=", 1)[1].rstrip(";")) // 8
        if line == "CONTENT BEGIN":
            in_content = True
            continue
        if not in_content or not line or line == "END;" or line.startswith("--"):
            continue
        if ":" not in line or ".." in line:
            continue
        left, right = line.rstrip(";").split(":", 1)
        word = int(left.strip(), 16)
        value = int(right.strip(), 16)
        if lanes is None:
            raise ValueError(f"missing WIDTH in {path}")
        for lane in range(lanes):
            address = word * lanes + lane
            if address < size:
                data[address] = (value >> (lane * 8)) & 0xFF
    return data


def write_packed_mif(path: Path, data: bytes, words_per_region: int | None = None) -> None:
    words = []
    if words_per_region is None:
        regions = [data]
    else:
        regions = [data[n:n + SLOT_BYTES] for n in range(0, len(data), SLOT_BYTES)]
    for region in regions:
        for offset in range(0, len(region), 5):
            chunk = region[offset:offset + 5]
            chunk = chunk + bytes(5 - len(chunk))
            words.append(sum(value << (lane * 8) for lane, value in enumerate(chunk)))
        if words_per_region is not None:
            while len(words) % words_per_region:
                words.append(0)
    lines = [
        "-- Generated by tools/pack_core_roms.py; do not edit by hand.",
        f"DEPTH = {len(words)};",
        "WIDTH = 40;",
        "ADDRESS_RADIX = HEX;",
        "DATA_RADIX = HEX;",
        "CONTENT BEGIN",
    ]
    lines.extend(f"{address:05X}: {value:010X};" for address, value in enumerate(words))
    lines.append("END;")
    path.write_text("\n".join(lines) + "\n", encoding="ascii")


def main() -> None:
    builtin = parse_byte_mif(ROMS / "rom.mif", ROM_BYTES)
    write_packed_mif(ROMS / "rom_packed.mif", builtin)

    cartridges = bytearray(2 * SLOT_BYTES)
    cartridges[SLOT_BYTES:2 * SLOT_BYTES] = parse_packed_mif(
        ROMS / "scsi_diag.mif", SLOT_BYTES
    )
    write_packed_mif(
        ROMS / "cartridge_roms_packed.mif", cartridges, words_per_region=3277
    )


if __name__ == "__main__":
    main()
