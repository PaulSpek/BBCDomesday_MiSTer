#!/usr/bin/env python3
"""Install a 16 KiB VFS ROM into the unused Master sideways-ROM slot 8.

The source ROM is deliberately supplied as a path: it is third-party Acorn
software and is not copied as a separate binary into this repository.  The
generated MIF is the synthesis input used by the core.
"""

from __future__ import annotations

import argparse
from pathlib import Path


ROM_SIZE = 16 * 1024
ROM_BANK = 14


def parse_mif(path: Path) -> bytearray:
    data = bytearray(16 * ROM_SIZE)
    address = 0
    in_content = False
    for raw in path.read_text(encoding="ascii").splitlines():
        line = raw.strip()
        if line == "CONTENT BEGIN":
            in_content = True
            continue
        if not in_content or not line or line == "END;":
            continue
        if ":" not in line:
            continue
        left, right = line.rstrip(";").split(":", 1)
        address = int(left.strip(), 16)
        for value in right.split():
            data[address] = int(value, 16)
            address += 1
    return data


def write_mif(path: Path, data: bytes) -> None:
    lines = [
        "-- Generated by tools/pack_vfs_rom.py; do not edit by hand.",
        "DEPTH = 262144;",
        "WIDTH = 8;",
        "ADDRESS_RADIX = HEX;",
        "DATA_RADIX = HEX;",
        "CONTENT BEGIN",
    ]
    for address in range(0, len(data), 24):
        values = " ".join(f"{value:02X}" for value in data[address:address + 24])
        lines.append(f"{address:04X}: {values};")
    lines.append("END;")
    path.write_text("\n".join(lines) + "\n", encoding="ascii")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("rom", type=Path, help="third-party 16 KiB VFS.rom input")
    parser.add_argument("mif", type=Path, help="core rom.mif to update")
    args = parser.parse_args()
    rom = args.rom.read_bytes()
    if len(rom) != ROM_SIZE:
        raise SystemExit(f"expected a {ROM_SIZE}-byte VFS ROM, got {len(rom)} bytes")
    image = parse_mif(args.mif)
    start = ROM_BANK * ROM_SIZE
    image[start:start + ROM_SIZE] = rom
    write_mif(args.mif, image)


if __name__ == "__main__":
    main()
